import { chromium } from 'playwright-core'
const theme = process.argv[2] ?? 'day'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 960 } })
await ctx.addInitScript((t) => localStorage.setItem('z.pref.theme', t), theme)
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:5173/missions/new', { waitUntil: 'networkidle' })
const box = page.getByRole('combobox', { name: 'What should Z do?' })
await box.click()
await page.keyboard.type('For every critical finding opened this week in #defe')
await page.screenshot({ path: `e2e/out/launch-completion.${theme}.png` })
await page.keyboard.press('Enter')
await page.keyboard.type('check whether it is actually exploitable, then open one #jir')
await page.keyboard.press('Tab')
await page.keyboard.type('ticket per owning team. Hand the triage to @vuln')
await page.keyboard.press('Enter')
await page.getByRole('button', { name: /matches playbook/ }).click().catch(() => undefined)
await page.waitForTimeout(400)
await page.getByRole('button', { name: /Draft the plan/ }).click()
await page.waitForTimeout(800)
await page.screenshot({ path: `e2e/out/launch.${theme}.png`, fullPage: true })
await browser.close()
